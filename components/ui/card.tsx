import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { level?: 1 | 2 | 3; reticles?: boolean }
>(({ className, level = 1, reticles = false, ...props }, ref) => {
  const levelClass =
    level === 3
      ? "bg-[#101722] border-[#00ff66]/30 shadow-lg"
      : level === 2
      ? "bg-[#0b1017] border-white/10 hover:border-[#00ff66]/30"
      : "bg-[#080c10] border-white/10"

  return (
    <div
      ref={ref}
      className={cn(
        "relative rounded-sm border text-[#f8fafc] transition-colors",
        levelClass,
        className
      )}
      {...props}
    />
  )
})
Card.displayName = "Card"

